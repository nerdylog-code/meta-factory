/**
 * Content-Security-Policy for page HTML served from the isolated origin.
 *
 * `connect-src 'none'` is the load-bearing directive: a page generated by an
 * agent cannot exfiltrate data or fetch remote code, even if the model was
 * talked into embedding a beacon. Inline script/style are allowed because that
 * is what a self-contained generated page is made of.
 *
 * `frame-ancestors` names the SHELL origin explicitly rather than `'none'`.
 * A blanket `'none'` looks safer but makes the feature impossible — the shell
 * legitimately frames its own PageStage, and `'none'` blocked it (the iframe
 * rendered as a broken-page icon). Naming one origin is both stricter than
 * `*` and sufficient: no other site may frame a page.
 */
export function buildPageCsp(shellOrigin: string): string {
  return [
    "default-src 'none'",
    "script-src 'unsafe-inline'",
    "style-src 'unsafe-inline'",
    "img-src data:",
    "font-src data:",
    "connect-src 'none'",
    "form-action 'none'",
    "base-uri 'none'",
    `frame-ancestors ${shellOrigin}`,
  ].join('; ');
}

/** Default CSP for a page whose shell origin is not yet known. */
export const PAGE_CSP = buildPageCsp("'none'");

/**
 * Wraps page body content in a minimal document.
 *
 * The bridge shim is injected by the SERVER, not by the page, so a page cannot
 * opt out of `targetOrigin` restrictions or add message types.
 */
export function wrapPageHtml(args: { title: string; body: string; shellOrigin: string }): string {
  const safeTitle = escapeHtml(args.title);
  const shellOrigin = JSON.stringify(args.shellOrigin);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="${buildPageCsp(args.shellOrigin)}">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${safeTitle}</title>
<style>${PAGE_BASE_CSS}</style>
</head>
<body>
${args.body}
<script>
(function(){
  var SHELL = ${shellOrigin};
  // The only bridge a page gets. It posts to the exact shell origin, never '*'.
  window.factoryBridge = {
    navigate: function(path){ parent.postMessage({type:'navigate', path:String(path)}, SHELL); },
    copy: function(text){ parent.postMessage({type:'copy', text:String(text)}, SHELL); },
    requestPrompt: function(prompt){ parent.postMessage({type:'request_prompt', prompt:String(prompt)}, SHELL); }
  };
})();
</script>
</body>
</html>`;
}

function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c] ?? c,
  );
}

/**
 * Rejects page HTML that would break out of the sandbox assumptions.
 *
 * We do not sanitize arbitrary HTML (that is a losing game). Instead we refuse
 * the few constructs that would let a page re-parent itself or reach the
 * network through a mechanism CSP cannot block here.
 */
export function assertPageHtmlIsContained(html: string): void {
  const lower = html.toLowerCase();
  if (lower.includes('<meta http-equiv="refresh"') || lower.includes("<meta http-equiv='refresh'")) {
    throw new Error('Page HTML may not contain a meta refresh');
  }
  if (/<base[\s>]/i.test(html)) {
    throw new Error('Page HTML may not contain a <base> tag');
  }
}

