import { z } from 'zod';

/**
 * The ONLY messages a PageStage page may send to the main app.
 *
 * This is deliberately tiny. A generative UI is untrusted code running in the
 * user's browser; it gets no CommandBus access, so the best it can do is ask
 * the shell to do one of three safe things.
 */
export const PageBridgeMessageSchema = z.discriminatedUnion('type', [
  z
    .object({
      type: z.literal('navigate'),
      /** App-relative path, validated again by the shell. */
      path: z.string().min(1).max(500).regex(/^\//, 'path must start with /'),
    })
    .strict(),
  z
    .object({
      type: z.literal('copy'),
      text: z.string().max(20_000),
    })
    .strict(),
  z
    .object({
      type: z.literal('request_prompt'),
      /** The page asks the human to send a prompt to the agent. */
      prompt: z.string().min(1).max(4000),
    })
    .strict(),
]);

export type PageBridgeMessage = z.infer<typeof PageBridgeMessageSchema>;

export type BridgeValidation =
  | { ok: true; message: PageBridgeMessage }
  | { ok: false; reason: string };

/**
 * Validates an incoming postMessage payload.
 *
 * Rejects:
 *  - non-objects, unknown `type` values (no passthrough)
 *  - extra keys (`strict`), so a page cannot smuggle a payload to a future
 *    handler that trusts unvalidated fields
 */
export function validateBridgeMessage(raw: unknown): BridgeValidation {
  const parsed = PageBridgeMessageSchema.safeParse(raw);
  if (!parsed.success) {
    const first = parsed.error.issues[0];
    return {
      ok: false,
      reason: first ? `${first.path.join('.') || 'message'}: ${first.message}` : 'invalid message',
    };
  }
  return { ok: true, message: parsed.data };
}

